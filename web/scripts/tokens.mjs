// Generates src/design/tokens.css from ../design/tokens.json (the design token source of truth).
// Run with `npm run gen:tokens`. The output is committed; never edit it by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../design/tokens.json");
const out = resolve(here, "../src/design/tokens.css");
const tokens = JSON.parse(readFileSync(src, "utf8"));

// Fontsource registers self-hosted variable fonts as "<Family> Variable".
// Put that name first so the bundled files win, keeping the design names as fallbacks.
const SELF_HOSTED = ["Bricolage Grotesque", "Atkinson Hyperlegible Next"];
const withVariable = (stack) =>
  SELF_HOSTED.reduce(
    (s, fam) => s.replace(`"${fam}"`, `"${fam} Variable", "${fam}"`),
    stack,
  );

const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const plain = [...tokens.spacing.tokens, ...tokens.radius.tokens, ...tokens.size.tokens];
const decl = (name, value) => `  --${name}: ${value};`;
const themeBlock = (theme, indent = "") =>
  themed.map((t) => indent + decl(t.name, t.value[theme])).join("\n");

const lines = [
  "/* generated by scripts/tokens.mjs from design/tokens.json, do not edit */",
  "",
  ":root {",
  "  color-scheme: light;",
  themeBlock("light"),
  ...plain.map((t) => decl(t.name, t.value)),
  ...Object.entries(tokens.type.families).map(([k, v]) => decl(`font-${k}`, withVariable(v))),
  "}",
  "",
  "@media (prefers-color-scheme: dark) {",
  '  :root:not([data-theme="light"]) {',
  "    color-scheme: dark;",
  themeBlock("dark", "  "),
  "  }",
  "}",
  "",
  ':root[data-theme="dark"] {',
  "  color-scheme: dark;",
  themeBlock("dark"),
  "}",
];

for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    lines.push(
      "",
      `.t-${s.name} {`,
      `  font-family: var(--font-${group.family});`,
      `  font-size: ${s.fontSize};`,
      `  line-height: ${s.lineHeight};`,
      `  font-weight: ${s.fontWeight};`,
    );
    if (s.letterSpacing) lines.push(`  letter-spacing: ${s.letterSpacing};`);
    if (s.name === "caption") lines.push("  font-variant-numeric: tabular-nums;");
    if (s.name === "label") lines.push("  text-transform: uppercase;");
    lines.push("}");
  }
}

writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}`);
